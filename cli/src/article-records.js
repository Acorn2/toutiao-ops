import { createHash } from 'node:crypto';

export const CONTENT_PAGE = 'https://mp.toutiao.com/profile_v4/manage/content/all';
export const digest = value => createHash('sha256').update(value).digest('hex');
export function mediaKey(src) {
  try {
    const url = new URL(src);
    if (url.protocol !== 'https:' || url.username || url.password) return '';
    // Keep content and signature parameters in the identity, but persist only the digest.
    return `sha256:${digest(url.href)}`;
  } catch { return ''; }
}

// Self-contained so the exact same canonicalizer runs in the browser for source HTML and persisted DOM.
export function inspectContent(target) {
  const root = typeof target === 'string' ? document.createElement('div') : target;
  if (typeof target === 'string') root.innerHTML = target;
  const links = [], images = [];
  let textBefore = '';
  const raw = text => text.normalize('NFC').replace(/\r\n?/g, '\n');
  const block = new Set(['p', 'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'ul', 'ol', 'li', 'blockquote', 'pre', 'table', 'tr', 'th', 'td', 'hr']);
  function clean(parts, trim = false) {
    const merged = [];
    for (const part of parts) {
      if (part === '') continue;
      if (typeof part === 'string' && typeof merged.at(-1) === 'string') merged[merged.length - 1] += part;
      else merged.push(part);
    }
    const result = merged.filter((part, i) => typeof part !== 'string' || part.trim() !== '' ||
      !(block.has(merged[i - 1]?.[0]) || block.has(merged[i + 1]?.[0]) || (trim && (i === 0 || i === merged.length - 1))));
    if (trim) {
      if (typeof result[0] === 'string') result[0] = result[0].trimStart();
      if (typeof result.at(-1) === 'string') result[result.length - 1] = result.at(-1).trimEnd();
      // Browsers insert a caret BR at the end of editable paragraphs.
      if (result.at(-1)?.[0] === 'br') result.pop();
    }
    return result.filter(part => part !== '');
  }
  const children = node => clean([...node.childNodes].flatMap(walk));
  function walk(node) {
    if (node.nodeType === Node.TEXT_NODE) {
      textBefore += raw(node.textContent);
      return [raw(node.textContent).replace(/[\u200b\ufeff]/g, '').replace(/[\s\u00a0]+/g, ' ')];
    }
    if (node.nodeType !== Node.ELEMENT_NODE) return [];
    const name = node.tagName.toLowerCase();
    if (name === 'pre' || name === 'code') {
      const text = node.textContent.replace(/\r\n?/g, '\n'); textBefore += text;
      return [[name, text]]; // Do not collapse code indentation or line breaks.
    }
    if (name === 'img') {
      const index = images.length;
      images.push({ src: node.currentSrc || node.src, ready: node.complete && node.naturalWidth > 0, offset: textBefore.length });
      return [['img', index]];
    }
    if (name === 'br' || name === 'hr') return [[name]];
    // The editor's spelling checker decorates text without changing the article.
    if (name === 'typo' && node.getAttribute('ignoretag') === 'true'
      && node.getAttribute('data-origin') === node.textContent) return children(node);
    if (name === 'syl-inline') {
      const canonical = node.querySelector(':scope > templ > a.pgc-link[href]');
      const displayed = node.querySelector(':scope > mask > a.pgc-link[href]');
      if (canonical && displayed?.href === canonical.href) return walk(canonical);
    }
    if (name === 'a') {
      const index = links.length; links.push(node.href);
      // Native external link titles are generated by the platform and may change.
      if (node.classList.contains('pgc-link')) return [['external-link', index]];
      return [['a', index, children(node)]];
    }
    const alias = { div: 'p', b: 'strong', i: 'em', s: 'del', strike: 'del' };
    const tag = alias[name] || name;
    let parts = children(node);
    if (tag === 'p') {
      parts = clean(parts, true);
      return parts.length ? [['p', parts]] : [];
    }
    if (['span', 'font', 'tbody', 'thead', 'tfoot'].includes(tag)) return parts;
    if (tag === 'ol') return [['ol', Number(node.getAttribute('start') || 1), clean(parts, true)]];
    if (block.has(tag)) return [[tag, clean(parts, true)]];
    if (tag === 'input') return [['input', node.getAttribute('type'), !!node.checked]];
    return [[tag, parts]];
  }
  return { structure: clean(children(root), true), links, images };
}

export function contentSnapshot(value) {
  return {
    schema_version: 2,
    contentHash: digest(JSON.stringify(value.structure)),
    linksHash: digest(JSON.stringify(value.links)),
    images: value.images.map(image => ({ key: mediaKey(image.src), ready: image.ready, offset: image.offset })),
  };
}
export function recordId(url, fallback = '') {
  try {
    const parsed = new URL(url);
    for (const name of ['article_id', 'item_id', 'group_id', 'pgc_id', 'id']) {
      const value = parsed.searchParams.get(name);
      if (/^\d+$/.test(value || '')) return value;
    }
    return parsed.pathname.match(/\/(?:article\/|item\/|i)(\d+)/)?.[1] || (/^\d+$/.test(fallback) ? fallback : null);
  } catch { return /^\d+$/.test(fallback) ? fallback : null; }
}

export function matchesSnapshot(actual, expected) {
  return !!expected && expected.schema_version === 2 && actual.schema_version === 2
    && actual.contentHash === expected.contentHash && actual.linksHash === expected.linksHash
    && actual.images.length === expected.images.length
    && actual.images.every((image, i) => image.ready && image.key && image.key === expected.images[i].key);
}
